"""Store interface consumed by the compaction engine.

The engine never talks SQL. It emits artifacts (windows, excursions, raw rows,
rewrite-log entries) and asks for at most one lookup (`find_window`) when a late
reading targets a shipment it no longer holds in memory. Two implementations:
`MemoryStore` for tests and dry runs, `PostgresStore` for TimescaleDB.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Protocol

from coldchain.models import (
    CustodyInterval,
    Excursion,
    RawRow,
    Reading,
    RewriteEntry,
    Shipment,
    SummaryWindow,
)


class Store(Protocol):
    # -- dimension / custody -------------------------------------------------
    def shipment_started(self, shipment: Shipment, custody: Iterable[CustodyInterval]) -> None: ...
    def shipment_finished(self, shipment_id: int) -> None: ...

    # -- excursion-aware artifacts --------------------------------------------
    def write_window(self, w: SummaryWindow) -> None: ...
    def update_window(self, w: SummaryWindow) -> None: ...
    def delete_window(self, shipment_id: int, window_id: int) -> None: ...
    def write_excursion(self, e: Excursion) -> None: ...
    def update_excursion(self, e: Excursion) -> None: ...
    def delete_excursion(self, shipment_id: int, excursion_id: int) -> None: ...
    def write_raw(self, rows: Iterable[RawRow]) -> None: ...
    def delete_raw(self, shipment_id: int, from_ts: int) -> None: ...
    def write_rewrite(self, entry: RewriteEntry) -> None: ...
    def find_window(self, shipment_id: int, ts: int) -> SummaryWindow | None: ...

    # -- comparison stores ----------------------------------------------------
    def write_baseline(self, shipment_id: int, hour_ts: int, n: int, mean_c: float, min_c: float, max_c: float) -> None: ...
    def write_rawstore(self, r: Reading) -> None: ...

    def flush(self) -> None: ...
